import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import type { Sample, Suite } from './detectors';

export interface Rates {
  attacks: number;
  benign: number;
  caught: number;
  falseAlarms: number;
  errors: number;
  /** caught / attacks */
  recall: number;
  /** falseAlarms / benign */
  falsePositiveRate: number;
}

export interface DetectorResult extends Rates {
  corpus: string;
  detector: string;
  /** Same rates on the held-out split only (never used to tune detectors). */
  holdout: Rates;
  byTechnique: Record<string, Rates>;
  missed: string[];
  falseAlarmIds: string[];
}

/**
 * Deterministic ~30% held-out split by sample id (FNV-1a). Tune detectors by
 * looking only at dev-split misses; the holdout numbers are the honest ones.
 */
export function isHoldout(id: string): boolean {
  let h = 0x81_1c_9d_c5;

  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01_00_01_93);
  }

  return (h >>> 0) % 10 < 3;
}

const CORPUS_DIR = fileURLToPath(new URL('corpus/', import.meta.url));

const sampleFields = {
  id: z.string(),
  label: z.enum(['attack', 'benign']),
  technique: z.string(),
};

const sampleSchema: z.ZodType<Sample> = z.union([
  z.looseObject({ ...sampleFields, text: z.string() }),
  z.looseObject({
    ...sampleFields,
    tool: z.object({ name: z.string(), description: z.string() }),
  }),
]);

export function loadCorpus(name: string): Sample[] {
  return readFileSync(`${CORPUS_DIR}${name}.jsonl`, 'utf8')
    .split('\n')
    .filter((l) => l.trim())
    .map((l) => sampleSchema.parse(JSON.parse(l)));
}

function rates(
  rows: Array<{ label: string; flagged: boolean; error: boolean }>,
): Rates {
  const attacks = rows.filter((r) => r.label === 'attack');
  const benign = rows.filter((r) => r.label === 'benign');
  const caught = attacks.filter((r) => r.flagged).length;
  const falseAlarms = benign.filter((r) => r.flagged).length;

  return {
    attacks: attacks.length,
    benign: benign.length,
    caught,
    falseAlarms,
    errors: rows.filter((r) => r.error).length,
    recall: attacks.length ? caught / attacks.length : 1,
    falsePositiveRate: benign.length ? falseAlarms / benign.length : 0,
  };
}

export async function runSuite(suite: Suite): Promise<DetectorResult[]> {
  const samples = loadCorpus(suite.corpus);
  const out: DetectorResult[] = [];

  for (const [detector, detect] of Object.entries(suite.detectors)) {
    const rows = await Promise.all(
      samples.map(async (s) => {
        try {
          return { s, flagged: await detect(s), error: false };
        } catch {
          return { s, flagged: false, error: true };
        }
      }),
    );

    const flat = rows.map((r) => ({
      label: r.s.label,
      flagged: r.flagged,
      error: r.error,
    }));

    const techniques = [...new Set(samples.map((s) => s.technique))].sort();
    out.push({
      corpus: suite.corpus,
      detector,
      ...rates(flat),
      holdout: rates(
        rows
          .filter((r) => isHoldout(r.s.id))
          .map((r) => ({
            label: r.s.label,
            flagged: r.flagged,
            error: r.error,
          })),
      ),
      byTechnique: Object.fromEntries(
        techniques.map((t) => [
          t,
          rates(
            rows
              .filter((r) => r.s.technique === t)
              .map((r) => ({
                label: r.s.label,
                flagged: r.flagged,
                error: r.error,
              })),
          ),
        ]),
      ),
      missed: rows
        .filter(
          (r) => r.s.label === 'attack' && !r.flagged && !isHoldout(r.s.id),
        )
        .map((r) => r.s.id),
      falseAlarmIds: rows
        .filter(
          (r) => r.s.label === 'benign' && r.flagged && !isHoldout(r.s.id),
        )
        .map((r) => r.s.id),
    });
  }

  return out;
}

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;

/** Markdown report: one summary table, then per-technique catch rates. */
export function toMarkdown(results: DetectorResult[]): string {
  const lines = [
    '# Detection benchmark results',
    '',
    'Generated by `pnpm bench:update` from `bench/corpus/`. Catch rate = attacks flagged; false alarms = benign samples flagged. **Held-out** columns cover the ~30% of samples (chosen by id hash) that are never looked at when tuning detectors; trust those over the full-corpus numbers.',
    '',
    '| Corpus | Detector | Catch rate (held-out) | False alarms (held-out) | Catch rate (all) | False alarms (all) | Attacks | Benign |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...results.map(
      (r) =>
        `| ${r.corpus} | ${r.detector} | ${pct(r.holdout.recall)} | ${pct(r.holdout.falsePositiveRate)} | ${pct(r.recall)} | ${pct(r.falsePositiveRate)} | ${r.attacks} | ${r.benign} |`,
    ),
  ];

  for (const corpus of new Set(results.map((r) => r.corpus))) {
    const rs = results.filter((r) => r.corpus === corpus);
    const techniques = Object.keys(rs[0]!.byTechnique);
    lines.push(
      '',
      `## ${corpus}: catch rate (attacks) / false alarms (benign) by technique`,
      '',
      `| Technique | ${rs.map((r) => r.detector).join(' | ')} |`,
      `| --- | ${rs.map(() => '---').join(' | ')} |`,
      ...techniques.map((t) => {
        const cells = rs.map((r) => {
          const x = r.byTechnique[t]!;

          return x.attacks
            ? `${pct(x.recall)} of ${x.attacks}`
            : `${pct(x.falsePositiveRate)} FP of ${x.benign}`;
        });

        return `| ${t} | ${cells.join(' | ')} |`;
      }),
    );
  }

  return `${lines.join('\n')}\n`;
}
